#!/usr/bin/env bash
# regen-swaync-theme.sh
#
# Ported from Paul's original SwayNC section (Python GTK-4 version) to bash.
# Reads ~/.config/hypr-control-center/current-theme.json and writes a
# complete SwayNC style.css to ~/.config/swaync/style.css, then reloads
# the notification daemon.
#
# Auto-called by ThemeService on every theme apply. Safe to re-run.
# Backups the previous style.css → style.css.backup on first run.
#
# Dependencies: jq, swaync (optional — skipped if not installed)

set -u

THEME_JSON="${HOME}/.config/hypr-control-center/current-theme.json"
SWAYNC_DIR="${HOME}/.config/swaync"
SWAYNC_STYLE="${SWAYNC_DIR}/style.css"
SWAYNC_BACKUP="${SWAYNC_DIR}/style.css.backup"

# ── Early exits ──
if ! command -v swaync >/dev/null 2>&1; then
    echo "[swaync] swaync not installed, skipping"
    exit 0
fi

if [ ! -f "$THEME_JSON" ]; then
    echo "[swaync] no theme at $THEME_JSON, skipping"
    exit 0
fi

if ! command -v jq >/dev/null 2>&1; then
    echo "[swaync] jq not installed, cannot parse theme JSON"
    exit 1
fi

mkdir -p "$SWAYNC_DIR"

# ── Extract theme colors ──
hex6() {
    local raw
    raw=$(jq -r ".colors.$1 // empty" "$THEME_JSON" 2>/dev/null)
    raw="${raw#\#}"
    if [ ${#raw} -eq 8 ]; then raw="${raw:0:6}"; fi
    if [ ${#raw} -ne 6 ]; then echo "1e2127"; else echo "$raw"; fi
}

BG=$(hex6 bg0)
BG_ALT=$(hex6 bg1)
BG4=$(hex6 bg4)
FG=$(hex6 fg)
BLUE=$(hex6 blue)
RED=$(hex6 red)
THEME_NAME=$(jq -r '.name // "unknown"' "$THEME_JSON")

# Allow per-user font override via env
FONT_FAMILY="${SWAYNC_FONT:-JetBrainsMono Nerd Font}"
FONT_SIZE="${SWAYNC_FONT_SIZE:-14}"
BORDER_RADIUS="${SWAYNC_BORDER_RADIUS:-24}"
NOTIF_RADIUS="${SWAYNC_NOTIF_RADIUS:-24}"

echo "[swaync] Applying '$THEME_NAME'"
echo "  bg=#$BG  bg_alt=#$BG_ALT  fg=#$FG  accent=#$BLUE  urgent=#$RED"

# ── Backup (first run only) ──
if [ -f "$SWAYNC_STYLE" ] && [ ! -f "$SWAYNC_BACKUP" ]; then
    cp "$SWAYNC_STYLE" "$SWAYNC_BACKUP"
    echo "  ✓ backed up existing style.css → style.css.backup"
fi

# ── Generate complete style.css ──
cat > "$SWAYNC_STYLE" << CSSEOF
/* ═══════════════════════════════════════════════════════════════════════
   SwayNC Complete Theme — Auto-generated by Zen Shell v6.6
   Theme: $THEME_NAME
   Generated: $(date -Iseconds)
   DO NOT EDIT — regenerated on every theme apply via Zen Shell
   Backup: ~/.config/swaync/style.css.backup
   ═══════════════════════════════════════════════════════════════════════ */

@define-color background      #$BG;
@define-color background-alt  #$BG_ALT;
@define-color text            #$FG;
@define-color selected        #$BLUE;
@define-color hover           #$BG4;
@define-color urgent          #$RED;

* {
    color: @text;
    all: unset;
    font-size: ${FONT_SIZE}px;
    font-family: "$FONT_FAMILY", "Adwaita Sans", sans-serif;
    transition: 200ms;
}

.blank-window { background: transparent; }

