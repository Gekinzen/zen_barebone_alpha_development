.widget-inhibitors > button:hover { background: @hover; }
.widget-inhibitors > button > box > image { color: @text; }
.widget-inhibitors > button > box > label { color: @text; }
CSSEOF

echo "  ✓ wrote ${SWAYNC_STYLE}"

# ── Reload SwayNC ──
if command -v swaync-client >/dev/null 2>&1; then
    # Timeout the reload so a hung daemon doesn't block install.
    # timeout exits with 124 if it killed the process; treat it
    # as a non-fatal "daemon not responding".
    if timeout 3 swaync-client --reload-css >/dev/null 2>&1; then
        echo "  ✓ reloaded SwayNC CSS"
    else
        echo "  ⚠ swaync-client reload skipped (daemon may not be running yet)"
    fi
fi

# ── Start swaync daemon if not running ──
# CRITICAL: Must fully detach from parent shell. Otherwise even with
# nohup + & , if the parent is running under `... | sed ...`, the pipe
# stdout stays open because the daemon inherits it, and the parent
# script hangs forever waiting for the pipeline to close.
#
# Fix: setsid + redirect ALL descriptors explicitly + disown + sleep 0
# yield, so the daemon is a full session leader with no inherited file
# descriptors tying it to the installer.
if ! pgrep -x swaync >/dev/null 2>&1; then
    setsid swaync </dev/null >/dev/null 2>&1 &
    disown 2>/dev/null || true
    echo "  ✓ started swaync daemon (detached)"
fi

# Explicit exit so bash doesn't sit around waiting for children
exit 0
